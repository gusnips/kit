/**
 * Tailwind classes for a bare React Native app, built before Metro starts.
 *
 * NativeWind v5 and react-native-css resolve `className` at runtime against a compiled stylesheet.
 * Their own way of compiling it is a Metro transformer that hands the CSS step to
 * `@expo/metro-config`'s worker, which needs the `expo` package and its native modules. A bare app
 * has neither, so this runs the same two Expo-free stages itself:
 *
 *   1. the Tailwind v4 CLI compiles the app's `global.css` to plain CSS, finding the classes in the
 *      app's own files (Tailwind v4 has no `--content` flag; a file outside the app folder needs an
 *      `@source` line in `global.css`);
 *   2. react-native-css's compiler turns that CSS into the stylesheet its runtime reads.
 *
 * The output is a TypeScript module the app injects at launch with `StyleCollection.inject`.
 * Editing a `className` hot-reloads as usual; only a change to the CSS or the tokens needs a rebuild,
 * which is why the build runs in the `start`, `ios` and `android` scripts, before Metro.
 *
 * Both tools are resolved from the APP's folder, not from this package: the stylesheet has to be in
 * the format of the react-native-css the bundle will run, and `global.css` imports `tailwindcss`
 * from where the app installed it.
 */
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import type { ReactNativeCssStyleSheet } from "react-native-css/compiler";

type Compiler = typeof import("react-native-css/compiler");

/** A colour code needs where it cannot take a `className`: one utility class per scheme. */
export interface PaletteEntry {
  /** A class that paints this colour in light mode, such as `"bg-surface"`. */
  light: string;
  /** The same in dark mode, such as `"dark:bg-dark-surface"`. */
  dark: string;
}

export interface NativeCssOptions {
  /** The app's folder. The other paths are read from it. Default: the current folder. */
  root?: string;
  /** The Tailwind entry. Default: `global.css`. */
  input?: string;
  /** Where `stylesheet.ts` (and `colors.ts`) are written. Default: `src/generated`. */
  outDir?: string;
  /**
   * How many pixels one `rem` is. Default: 16, the web's.
   *
   * react-native-css's own default is 14, React Native's root font size, and that silently shrinks
   * every rem-based size by an eighth: body text from 14 to 12.25 px and `h-12` from 48 to 42 px,
   * against tokens written for the web. A `:root { font-size }` in the CSS does not fix it
   * reliably, so the number is passed to the compiler instead.
   */
  rem?: number;
  /**
   * Hex colours for what cannot take a `className`: an icon's `color`, the navigation theme, the
   * status bar. Each name maps to a class in each scheme, and `colors.ts` gets the hex those classes
   * compile to. Read from the stylesheet itself, so a change of tokens cannot restyle the classes
   * and leave the icons in the old colours, which is what a hand-copied list of hex values did.
   */
  palette?: Record<string, PaletteEntry>;
}

export interface NativeCssResult {
  /** How many classes the stylesheet holds. */
  classes: number;
  /** The files written, as absolute paths. */
  files: string[];
}

/**
 * ```ts
 * await buildNativeCss(); // global.css → src/generated/stylesheet.ts
 * ```
 */
export async function buildNativeCss(options: NativeCssOptions = {}): Promise<NativeCssResult> {
  const root = resolve(options.root ?? ".");
  const input = resolve(root, options.input ?? "global.css");
  const outDir = resolve(root, options.outDir ?? "src/generated");
  const rem = options.rem ?? 16;
  if (!(rem > 0)) throw new Error(`buildNativeCss: rem must be a positive number, not ${rem}.`);

  const fromApp = createRequire(join(root, "package.json"));
  // Before Tailwind, so a missing react-native-css fails in a moment rather than after a compile.
  const compiler = loadCompiler(fromApp);
  const css = await runTailwind(fromApp, root, input);
  const stylesheet = compiler.compile(css, { inlineRem: rem }).stylesheet();
  dropUnmappable(stylesheet);

  await mkdir(outDir, { recursive: true });
  const banner = `// Generated by gusnips-native-css from ${relative(root, input)}. Do not edit: run it again.\n`;
  const stylesheetFile = join(outDir, "stylesheet.ts");
  await writeFile(
    stylesheetFile,
    `${banner}\nimport type { ReactNativeCssStyleSheet } from "react-native-css/compiler";\n\n` +
      `export const stylesheet: ReactNativeCssStyleSheet = ${JSON.stringify(stylesheet)};\n`,
  );
  const files = [stylesheetFile];

  const { palette } = options;
  if (palette) {
    const scheme = (mode: keyof PaletteEntry) =>
      Object.fromEntries(
        Object.entries(palette).map(([name, entry]) => [
          name,
          colorOf(stylesheet, entry[mode], root),
        ]),
      );
    const colors = { light: scheme("light"), dark: scheme("dark") };
    const colorsFile = join(outDir, "colors.ts");
    await writeFile(
      colorsFile,
      `${banner}\nexport const COLORS = ${JSON.stringify(colors, null, 2)};\n`,
    );
    files.push(colorsFile);
  }

  return { classes: Array.isArray(stylesheet.s) ? stylesheet.s.length : 0, files };
}

async function runTailwind(fromApp: NodeRequire, root: string, input: string): Promise<string> {
  const cli = tailwindCli(fromApp);
  // Out of the app's tree, so building reads the app and writes only `outDir`. Kept when the
  // compile fails, because the half-written CSS is the first thing worth reading.
  const work = await mkdtemp(join(tmpdir(), "gusnips-native-css-"));
  const out = join(work, "tailwind.css");
  const run = spawnSync(process.execPath, [cli, "-i", input, "-o", out], {
    cwd: root,
    encoding: "utf-8",
    // The compile takes seconds. A hung CLI with no deadline holds `bun run start` forever.
    timeout: 120_000,
  });
  if (run.error !== undefined) throw new Error(`tailwindcss did not finish: ${run.error.message}`);
  if (run.status !== 0)
    throw new Error(
      `tailwindcss could not compile ${input}` +
        `${run.stderr ? `:\n${run.stderr.slice(0, 1000)}` : ""}\n(work folder kept at ${work})`,
    );
  const css = await readFile(out, "utf-8");
  await rm(work, { recursive: true, force: true });
  return css;
}

function tailwindCli(fromApp: NodeRequire): string {
  let manifestPath: string;
  try {
    manifestPath = fromApp.resolve("@tailwindcss/cli/package.json");
  } catch {
    throw new Error(missing("@tailwindcss/cli"));
  }
  const manifest: { bin?: string | Record<string, string> } = fromApp(manifestPath);
  const bin = typeof manifest.bin === "string" ? manifest.bin : manifest.bin?.["tailwindcss"];
  if (!bin) throw new Error(`@tailwindcss/cli at ${manifestPath} names no tailwindcss bin.`);
  return join(dirname(manifestPath), bin);
}

/**
 * The CommonJS build, on purpose: react-native-css's ES module build imports `debug` by a named
 * export Node cannot see in a CommonJS package, so it does not load under plain Node (bun forgives
 * it). `require` loads the build that works under both.
 */
function loadCompiler(fromApp: NodeRequire): Compiler {
  let compiler: Compiler;
  try {
    compiler = fromApp("react-native-css/compiler");
  } catch (error) {
    if (isNotFound(error)) throw new Error(missing("react-native-css"));
    throw error;
  }
  refuseBrokenLightningcss(fromApp);
  return compiler;
}

/**
 * lightningcss 1.30.2 breaks react-native-css's compiler. react-native-css checks for it and means
 * to throw, but the check sits inside a `try` whose `catch` is empty, so the throw is swallowed and
 * the build goes on. This asks the same copy its loader picks: the one under `@expo/metro-config`
 * first (a peer of react-native-css, so bun installs it), then its own.
 *
 * That order is also why a devDependency on lightningcss does not fix it. Pin it with `overrides`
 * in the root `package.json`, which reaches every copy.
 */
function refuseBrokenLightningcss(fromApp: NodeRequire): void {
  const fromCss = createRequire(fromApp.resolve("react-native-css/package.json"));
  const candidates: NodeRequire[] = [];
  try {
    candidates.push(createRequire(fromCss.resolve("@expo/metro-config/package.json")));
  } catch {
    // No expo config beside it: react-native-css loads its own lightningcss.
  }
  candidates.push(fromCss);
  for (const from of candidates) {
    let version: string;
    try {
      const manifest: { version: string } = from("lightningcss/package.json");
      version = manifest.version;
    } catch {
      continue;
    }
    if (version === "1.30.2")
      throw new Error(
        "lightningcss 1.30.2 breaks react-native-css's compiler. Pin it to 1.30.1 with " +
          '"overrides": { "lightningcss": "1.30.1" } in the root package.json, or move to a newer one.',
      );
    return;
  }
}

/**
 * Tailwind finds class names by reading source as text, so a React Native style key such as
 * `transform` (an Animated style needs one) becomes a candidate. `transform` IS a Tailwind utility,
 * so it compiles, but its value cannot map to React Native and comes out `null`, which then fails
 * the app's typecheck on the generated file. Nobody can use it as a class on a phone, so it is
 * dropped here rather than banning a JavaScript word from every source file.
 */
function dropUnmappable(stylesheet: ReactNativeCssStyleSheet): void {
  if (!Array.isArray(stylesheet.s)) return;
  stylesheet.s = stylesheet.s.filter(
    (entry) => !(Array.isArray(entry) && entry[0] === "transform"),
  );
}

function colorOf(stylesheet: ReactNativeCssStyleSheet, className: string, root: string): string {
  const entry = Array.isArray(stylesheet.s)
    ? stylesheet.s.find((each) => Array.isArray(each) && each[0] === className)
    : undefined;
  const hex = entry ? JSON.stringify(entry[1]).match(/#[0-9a-fA-F]{3,8}\b/)?.[0] : undefined;
  if (hex === undefined)
    throw new Error(
      `No colour for "${className}" in the compiled stylesheet. Tailwind writes only the classes ` +
        `it finds in the app's files, so put "${className}" in a file under ${root} (a list of ` +
        "the palette's classes beside the code that reads the colours keeps them found).",
    );
  return hex;
}

function missing(name: string): string {
  return (
    `${name} is not installed in the app. gusnips-native-css reads it from the app's own ` +
    "packages: bun add react-native-css && bun add -d @tailwindcss/cli tailwindcss"
  );
}

function isNotFound(error: unknown): boolean {
  return error instanceof Error && "code" in error && error.code === "MODULE_NOT_FOUND";
}
